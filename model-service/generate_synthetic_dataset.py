"""
Synthetic Dataset Generator for Customer Return Risk Intelligence System.

This module generates a realistic, production-grade synthetic dataset representing
1-to-many customer order and return relationships. Each customer has multiple order
transactions and multiple return events (ranging from 0 up to 25+ returns per user),
simulating real-world e-commerce return abuse and risk patterns.

Key Features & Parameters Generated:
- User_ID: Unique customer identifier (e.g., CUST-1001)
- Order_ID: Unique transaction order ID (e.g., ORD-50001)
- Return_ID: Unique return event identifier if returned
- Product_Category: Product classification (Electronics, Fashion, Home, Luxury, Beauty)
- Product_Price: Monetary price per unit item
- Order_Quantity: Number of units purchased
- Return_Status: Transaction status ('Returned' or 'Completed')
- Return_Reason: Standardized return reason claims
- Order_Date: Date when order was placed
- Return_Date: Date when return request was filed
"""

import os
import random
from datetime import datetime, timedelta
import pandas as pd
import numpy as np


def generate_customer_profiles(num_customers=500):
    """
    Generates customer profile archetypes categorized into distinct risk tiers.

    Parameters:
    - num_customers (int): Total number of customer profiles to generate.

    Returns:
    - list of dict: Array of customer profile parameters controlling transaction behavior.
    """
    profiles = []
    
    # Define distribution of risk archetypes: 60% Low, 20% Medium, 15% High, 5% Critical
    tier_counts = {
        'Low': int(num_customers * 0.60),
        'Medium': int(num_customers * 0.20),
        'High': int(num_customers * 0.15),
        'Critical': num_customers - int(num_customers * 0.60) - int(num_customers * 0.20) - int(num_customers * 0.15)
    }

    cust_index = 1000

    for tier, count in tier_counts.items():
        for _ in range(count):
            cust_index += 1
            user_id = f"CUST-{cust_index}"

            if tier == 'Low':
                order_count = random.randint(12, 40)
                return_prob = random.uniform(0.0, 0.08)  # 0% - 8% return rate
                high_value_pref = random.uniform(0.1, 0.3)
                suspicious_reason_prob = 0.05
            elif tier == 'Medium':
                order_count = random.randint(10, 30)
                return_prob = random.uniform(0.12, 0.25)  # 12% - 25% return rate
                high_value_pref = random.uniform(0.2, 0.5)
                suspicious_reason_prob = 0.20
            elif tier == 'High':
                order_count = random.randint(15, 35)
                return_prob = random.uniform(0.35, 0.60)  # 35% - 60% return rate (Abusive)
                high_value_pref = random.uniform(0.5, 0.8)
                suspicious_reason_prob = 0.55
            else:  # Critical
                order_count = random.randint(20, 50)
                return_prob = random.uniform(0.65, 0.90)  # 65% - 90% return rate (Extreme Abuse)
                high_value_pref = random.uniform(0.7, 0.95)
                suspicious_reason_prob = 0.80

            profiles.append({
                'user_id': user_id,
                'tier': tier,
                'order_count': order_count,
                'return_prob': return_prob,
                'high_value_pref': high_value_pref,
                'suspicious_reason_prob': suspicious_reason_prob
            })

    return profiles


def generate_synthetic_transactions(profiles):
    """
    Simulates individual orders and return records for each customer profile.

    Parameters:
    - profiles (list of dict): Archetype configurations generated by generate_customer_profiles.

    Returns:
    - pd.DataFrame: Raw transactional dataset containing 1-to-many customer-return relations.
    """
    categories = {
        'Electronics': (150.0, 1500.0),
        'Fashion': (30.0, 250.0),
        'Home': (40.0, 500.0),
        'Luxury': (500.0, 3500.0),
        'Beauty': (20.0, 120.0)
    }

    standard_reasons = ["Size did not fit", "Changed mind", "Bought by mistake", "Color different than picture"]
    suspicious_reasons = ["Defective item", "Wrong item delivered", "Not as described", "Item damaged in transit", "Empty box claimed"]

    records = []
    base_date = datetime.now() - timedelta(days=365)
    order_id_counter = 50000
    return_id_counter = 80000

    for profile in profiles:
        user_id = profile['user_id']
        num_orders = profile['order_count']

        for i in range(num_orders):
            order_id_counter += 1
            order_id = f"ORD-{order_id_counter}"
            
            # Generate realistic order date spread across the past year
            days_offset = random.randint(0, 350)
            order_date = base_date + timedelta(days=days_offset)

            # Determine product category and price
            if random.random() < profile['high_value_pref']:
                category = random.choice(['Electronics', 'Luxury'])
            else:
                category = random.choice(['Fashion', 'Home', 'Beauty'])

            min_price, max_price = categories[category]
            price = round(random.uniform(min_price, max_price), 2)
            quantity = random.choices([1, 2, 3], weights=[0.8, 0.15, 0.05])[0]

            # Determine if this specific order is returned
            is_returned = random.random() < profile['return_prob']
            return_status = "Returned" if is_returned else "Completed"
            
            return_id = ""
            return_reason = ""
            return_date_str = ""

            if is_returned:
                return_id_counter += 1
                return_id = f"RET-{return_id_counter}"
                
                # Returns occur within 1 to 25 days after order placement
                return_days_later = random.randint(1, 25)
                return_date = order_date + timedelta(days=return_days_later)
                return_date_str = return_date.strftime("%Y-%m-%d")

                # Select return reason based on profile suspiciousness probability
                if random.random() < profile['suspicious_reason_prob']:
                    return_reason = random.choice(suspicious_reasons)
                else:
                    return_reason = random.choice(standard_reasons)

            records.append({
                'User_ID': user_id,
                'Order_ID': order_id,
                'Return_ID': return_id,
                'Product_Category': category,
                'Product_Price': price,
                'Order_Quantity': quantity,
                'Return_Status': return_status,
                'Return_Reason': return_reason,
                'Order_Date': order_date.strftime("%Y-%m-%d"),
                'Return_Date': return_date_str
            })

    return pd.DataFrame(records)


def main():
    """
    Main execution pipeline to generate and export synthetic customer returns dataset.
    """
    print("Generating customer profile archetypes...")
    profiles = generate_customer_profiles(num_customers=600)

    print(f"Simulating 1-to-many transactions for {len(profiles)} customers...")
    df = generate_synthetic_transactions(profiles)

    output_dir = os.path.dirname(os.path.abspath(__file__))
    output_path = os.path.join(output_dir, 'ecommerce_returns_synthetic_data.csv')

    df.to_csv(output_path, index=False)
    print(f"Synthetic dataset successfully exported to: {output_path}")
    print(f"Total Transactions: {len(df)}")
    print(f"Total Returns: {len(df[df['Return_Status'] == 'Returned'])}")
    print(f"Unique Customers: {df['User_ID'].nunique()}")


if __name__ == "__main__":
    main()
